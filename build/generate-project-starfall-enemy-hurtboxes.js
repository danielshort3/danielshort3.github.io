#!/usr/bin/env node
'use strict';

// Derive exact solid-pixel combat masks from the production actor layer. This
// does not change art, terrain collision, registration, or animation timing.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const sharp = require('sharp');

const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(ROOT, 'js/games/project-starfall/data/enemy-hurtboxes.js');
const INVENTORY = path.join(ROOT, 'asset-sources/project-starfall/overhaul-v1/enemies/inventory.json');
const ALPHA_THRESHOLD = 64;

function encodeRows(rows) {
  const first = rows.findIndex(row => row.length);
  if (first < 0) return Buffer.from([0, 0]).toString('base64');
  let last = rows.length - 1;
  while (!rows[last].length) last -= 1;
  const nibbles = [];
  const byte = value => nibbles.push(value >> 4, value & 15);
  let previous = [];
  for (let y = first; y <= last;) {
    const row = rows[y];
    let repeat = 1;
    while (repeat < 16 && y + repeat <= last &&
      rows[y + repeat].length === row.length && rows[y + repeat].every((value, index) => value === row[index])) repeat += 1;
    const count = row.length / 2;
    nibbles.push(Math.min(15, count), repeat - 1);
    if (count >= 15) byte(count);
    row.forEach((value, index) => {
      const delta = value - (previous[index] || 0);
      const zigzag = delta < 0 ? -delta * 2 - 1 : delta * 2;
      if (zigzag < 15) nibbles.push(zigzag);
      else {
        nibbles.push(15);
        byte(value);
      }
    });
    previous = row;
    y += repeat;
  }
  const bytes = [first, last - first + 1];
  for (let index = 0; index < nibbles.length; index += 2) bytes.push((nibbles[index] << 4) | (nibbles[index + 1] || 0));
  return Buffer.from(bytes).toString('base64');
}

async function generate() {
  const inventory = JSON.parse(fs.readFileSync(INVENTORY, 'utf8').replace(/^\uFEFF/, ''));
  const format = inventory.productionFormat;
  const sheets = {};
  const masks = [];
  const maskIndexByHash = new Map();
  let frameCount = 0;
  for (const item of inventory.items) {
    const sheet = item.replacement && item.replacement.sheet;
    if (!sheet) throw new Error(`${item.fileId}: production replacement is missing.`);
    const input = fs.readFileSync(path.join(ROOT, sheet));
    const sha256 = crypto.createHash('sha256').update(input).digest('hex');
    if (sha256 !== item.replacement.sheetSha256) throw new Error(`${item.fileId}: inventory hash is stale.`);
    const { data, info } = await sharp(input).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    if (info.width !== format.width || info.height !== format.height || info.channels !== 4) throw new Error(`${sheet}: unsupported sheet dimensions/channels.`);
    let maskIndex = maskIndexByHash.get(sha256);
    if (maskIndex === undefined) {
      maskIndex = masks.length;
      const frames = [];
      for (let row = 0; row < format.rows; row += 1) {
        for (let column = 0; column < format.columns; column += 1) {
          const rows = [];
          for (let y = 0; y < format.frameHeight; y += 1) {
            const runs = [];
            let start = -1;
            for (let x = 0; x <= format.frameWidth; x += 1) {
              const visible = x < format.frameWidth && data[((row * format.frameHeight + y) * info.width + column * format.frameWidth + x) * 4 + 3] >= ALPHA_THRESHOLD;
              if (visible && start < 0) start = x;
              if (!visible && start >= 0) {
                runs.push(start, x);
                start = -1;
              }
            }
            rows.push(runs);
          }
          frames.push(encodeRows(rows));
        }
      }
      masks.push(frames);
      maskIndexByHash.set(sha256, maskIndex);
    }
    sheets[sheet] = { sha256, frameWidth: format.frameWidth, frameHeight: format.frameHeight, columns: format.columns, rows: format.rows, maskIndex };
    frameCount += format.rows * format.columns;
  }
  const data = { schema: 'starfall-enemy-hurtboxes-v1', encoding: 'scanline-delta-nibbles-v1', alphaThreshold: ALPHA_THRESHOLD, sheets, masks };
  const source = `// Generated by build/generate-project-starfall-enemy-hurtboxes.js. Do not edit.\n(function initProjectStarfallEnemyHurtboxesData(global) {\n  'use strict';\n  const data = ${JSON.stringify(data)};\n  global.ProjectStarfallEnemyHurtboxesData = data;\n  if (typeof module === 'object' && module.exports) module.exports = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n`;
  if (Buffer.byteLength(source) > 950 * 1024) throw new Error(`Enemy mask source exceeds the 950 KiB budget: ${Buffer.byteLength(source)} bytes.`);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(OUTPUT) || fs.readFileSync(OUTPUT, 'utf8') !== source) throw new Error('Enemy hurtboxes are stale. Run node build/generate-project-starfall-enemy-hurtboxes.js.');
  } else fs.writeFileSync(OUTPUT, source);
  console.log(JSON.stringify({ sheets: Object.keys(sheets).length, frames: frameCount, uniqueMasks: masks.length * format.rows * format.columns, alphaThreshold: ALPHA_THRESHOLD, bytes: Buffer.byteLength(source), output: path.relative(ROOT, OUTPUT).replace(/\\/g, '/') }));
}

if (require.main === module) generate().catch(error => { console.error(error.message); process.exitCode = 1; });
module.exports = { encodeRows, generate, ALPHA_THRESHOLD };
